"""Generate color-only adapters without changing the original readers' stylesheets.

Existing variable-based declarations use the shared aliases. Literal UI colors
are adapted by declaration role; exercise images and SVG fill/stroke stay intact.
"""
import re
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
SOURCES={'library':'assets/library.css','photoshop':'manuals/photoshop/assets/style.css','premiere':'manuals/premiere/style.css','after-effects':'manuals/after-effects/web/styles.css'}
COLOR=re.compile(r'#[\da-fA-F]{3,8}\b|\b(?:white|black)\b')

def rules(css):
    css=re.sub(r'/\*.*?\*/','',css,flags=re.S)
    while css.strip():
        start=css.find('{')
        if start<0:return
        depth=1;end=start+1
        while depth:
            if css[end]=='{':depth+=1
            elif css[end]=='}':depth-=1
            end+=1
        yield css[:start].strip(),css[start+1:end-1]
        css=css[end:]

def adapt(css):
    result=[]
    for selector,body in rules(css):
        if selector.startswith('@'):
            if selector.startswith('@media') and 'print' not in selector:
                nested=adapt(body)
                if nested:result.append(selector+'{'+nested+'}')
            continue
        if ':root' in selector or selector.startswith('html['):continue
        declarations=[]
        for declaration in body.split(';'):
            if ':' not in declaration:continue
            prop,value=declaration.split(':',1);prop=prop.strip()
            if prop.startswith('--') or not COLOR.search(value):continue
            if prop in ('color','background','background-color','border','border-color','border-left','border-top','border-bottom','border-right','outline','outline-color','accent-color'):
                role='ink' if prop=='color' else 'paper' if prop.startswith('background') else 'line'
                if prop in ('accent-color','outline','outline-color'):role='accent'
                if prop=='color' and any(x in selector for x in ('muted','small','caption','label','tiny','note')):role='muted'
                if prop=='color' and any(x in selector for x in ('.wrong','.bad')):role='bad'
                if prop=='color' and any(x in selector for x in ('.correct','.good')):role='good'
                if prop.startswith('background') and any(x in selector for x in (':hover','.active','.selected','.note','code','.done','.completed')):role='soft'
                if prop.startswith('background') and '.dot:before' in selector:role='accent'
                if prop.startswith('border') and any(x in selector for x in ('.wrong','.bad')):role='bad'
                if prop.startswith('background') and ('gradient' in value):value='var(--t-soft)'
                else:value=COLOR.sub('var(--t-'+role+')',value)
                declarations.append(prop+':'+value)
        if declarations:
            selectors=','.join('html[data-palette] '+s.strip() for s in selector.split(','))
            result.append(selectors+'{'+ ';'.join(declarations)+'}')
    return '\n'.join(result)

def build():
    for app,source in SOURCES.items():
        extra='\nhtml[data-palette] .diagram svg{background:#f8fbfb;border-radius:8px}\n' if app=='after-effects' else ''
        (ROOT/'assets'/('palette-'+app+'.css')).write_text('/* Generated by scripts/palettes.py; original layout and media unchanged. */\n'+adapt((ROOT/source).read_text())+'\n'+extra)

def reader_head(app):
    css=(ROOT/'assets/palette.css').read_text()+(ROOT/'assets'/('palette-'+app+'.css')).read_text()
    js=(ROOT/'assets/palette.js').read_text()
    return '<style>'+css+'</style><script>'+js+'</script>'
if __name__=='__main__':build()
